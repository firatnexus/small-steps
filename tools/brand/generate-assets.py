#!/usr/bin/env python3
"""Small Steps v3.6 — brand asset generator.

Renders every raster brand asset from one logo definition:
  * icon.svg (PWA / README, web colorway)
  * Android launcher PNGs (legacy, round, adaptive foreground) per density
  * Android adaptive icon vectors (foreground + monochrome)
  * 11 Android splash PNGs (Things "Mist" canvas, app colorway)
  * social-preview.png (1280x640, web colorway)

Logo: three rising steps ending at a small destination dot on a rounded tile.
  app (Things)  : tile #2576eb, steps + dot #ffffff
  web (Todoist) : tile #25221e, steps #fefdfc, dot #e34432

Usage:  pip install playwright && playwright install chromium
        python3 tools/brand/generate-assets.py
"""
import asyncio, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "android/app/src/main/res"

PATH_D = "M16.5 70H32.5V56H48.5V42H64.5V28"   # 96-unit grid, centred on (48,48)
DOT = (77.5, 28, 6.5)
STROKE = 9

APP = dict(tile="#2576eb", mark="#ffffff", dot="#ffffff")
WEB = dict(tile="#25221e", mark="#fefdfc", dot="#e34432")
MIST = "#f2f5f7"; INK_APP = "#303336"; FOG = "#55606e"


def mark(c, transform=""):
    cx, cy, r = DOT
    return (f'<g transform="{transform}"><path d="{PATH_D}" fill="none" stroke="{c["mark"]}" '
            f'stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{c["dot"]}"/></g>')


def tile_svg(c, size=96, round_=False, scale=1.0):
    shape = (f'<circle cx="48" cy="48" r="48" fill="{c["tile"]}"/>' if round_
             else f'<rect width="96" height="96" rx="22" fill="{c["tile"]}"/>')
    t = f"translate(48 48) scale({scale}) translate(-48 -48)"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" width="{size}" '
            f'height="{size}">{shape}{mark(c, t)}</svg>')


def foreground_svg(size):
    # 108dp canvas, 66dp safe zone → mark ~52dp wide
    t = "translate(54 54) scale(0.72) translate(-48 -48)"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="{size}" '
            f'height="{size}">{mark(APP, t)}</svg>')


def icon_svg_file():
    t = "scale(5.3333)"
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Small Steps">\n'
            f'  <rect width="512" height="512" rx="117" fill="{WEB["tile"]}"/>\n'
            f'  <g transform="{t}">\n'
            f'    <path d="{PATH_D}" fill="none" stroke="{WEB["mark"]}" stroke-width="{STROKE}" '
            'stroke-linecap="round" stroke-linejoin="round"/>\n'
            f'    <circle cx="{DOT[0]}" cy="{DOT[1]}" r="{DOT[2]}" fill="{WEB["dot"]}"/>\n'
            '  </g>\n</svg>\n')


def vector_xml(color, name):
    # Android VectorDrawable for the adaptive foreground / monochrome layer
    cx, cy, r = DOT
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Small Steps v3.6 — {name} (generated by tools/brand/generate-assets.py) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="19.44"
        android:translateY="19.44"
        android:scaleX="0.72"
        android:scaleY="0.72">
        <path
            android:pathData="{PATH_D}"
            android:strokeColor="{color}"
            android:strokeWidth="{STROKE}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
        <path
            android:pathData="M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0"
            android:fillColor="{color}" />
    </group>
</vector>
'''


def splash_html(w, h):
    s = min(w, h)
    tile = round(s * 0.24); name = round(s * 0.075); gap = round(s * 0.05)
    return f'''<html><head><style>
html,body{{margin:0;width:{w}px;height:{h}px;background:{MIST};}}
body{{display:flex;flex-direction:column;align-items:center;justify-content:center;
font-family:"Roboto",sans-serif;}}
.t{{width:{tile}px;height:{tile}px;filter:drop-shadow(0 {s*0.006}px {s*0.02}px rgba(0,0,0,.12));}}
h1{{margin:{gap}px 0 0;font-weight:700;font-size:{name}px;color:{INK_APP};letter-spacing:-.01em;}}
</style></head><body><div class="t">{tile_svg(APP, tile)}</div><h1>Small Steps</h1></body></html>'''


def social_html():
    return f'''<html><head><style>
@font-face{{font-family:Inter;src:url("file://{ROOT}/fonts/inter-latin.woff2") format("woff2");font-weight:100 900;}}
html,body{{margin:0;width:1280px;height:640px;background:#fefdfc;font-family:Inter,sans-serif;overflow:hidden}}
.band{{position:absolute;inset:0 0 auto 0;height:420px;background:#fff6f0;border-radius:0 0 50% 50%/0 0 60px 60px}}
.wrap{{position:relative;display:flex;align-items:center;gap:56px;padding:0 120px;height:100%}}
.eb{{color:#cf3520;font-weight:700;font-size:22px;letter-spacing:.08em;text-transform:uppercase}}
h1{{margin:10px 0 14px;font-size:92px;font-weight:750;letter-spacing:-.035em;color:#25221e;line-height:1}}
p{{margin:0;font-size:30px;color:#6f6c69;line-height:1.35;max-width:640px}}
.pill{{display:inline-block;margin-top:28px;background:#cf3520;color:#fff;font-weight:650;font-size:24px;
padding:14px 26px;border-radius:8px}}
</style></head><body><div class="band"></div><div class="wrap">
<div style="filter:drop-shadow(0 10px 24px rgba(37,34,30,.18))">{tile_svg(WEB, 240)}</div>
<div><div class="eb">Pomodoro · Tasks · Offline</div><h1>Small Steps</h1>
<p>Break big things into smaller steps. Focus on one, and leave yourself room to breathe.</p>
<span class="pill">firatnexus.github.io/small-steps</span></div></div></body></html>'''


async def main():
    from playwright.async_api import async_playwright
    (ROOT / "icon.svg").write_text(icon_svg_file())
    (RES / "drawable-v24/ic_launcher_foreground.xml").write_text(vector_xml("#FFFFFF", "adaptive foreground"))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector_xml("#000000", "themed-icon monochrome"))
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'  <color name="ic_launcher_background">{APP["tile"]}</color>\n</resources>\n')

    dens = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page()

        async def svg_png(svg, size, out):
            await pg.set_viewport_size({"width": size, "height": size})
            await pg.set_content(f'<html><body style="margin:0;background:transparent">{svg}</body></html>')
            await pg.screenshot(path=str(out), omit_background=True,
                                clip={"x": 0, "y": 0, "width": size, "height": size})

        for d, k in dens.items():
            folder = RES / f"mipmap-{d}"
            n = round(48 * k)
            # legacy icon: tile inset like the Material legacy grid (44/48)
            inset = f'<div style="padding:{round(n*2/48)}px">{tile_svg(APP, n - 2*round(n*2/48))}</div>'
            await svg_png(inset, n, folder / "ic_launcher.png")
            await svg_png(tile_svg(APP, n, round_=True, scale=0.86), n, folder / "ic_launcher_round.png")
            await svg_png(foreground_svg(round(108 * k)), round(108 * k), folder / "ic_launcher_foreground.png")

        sizes = {"mdpi": (320, 480), "hdpi": (480, 800), "xhdpi": (720, 1280),
                 "xxhdpi": (960, 1600), "xxxhdpi": (1280, 1920)}
        land = {"mdpi": (480, 320), "hdpi": (800, 480), "xhdpi": (1280, 720),
                "xxhdpi": (1600, 960), "xxxhdpi": (1920, 1280)}
        jobs = [(RES / "drawable/splash.png", (480, 320))]
        jobs += [(RES / f"drawable-port-{d}/splash.png", s) for d, s in sizes.items()]
        jobs += [(RES / f"drawable-land-{d}/splash.png", s) for d, s in land.items()]
        for out, (w, h) in jobs:
            await pg.set_viewport_size({"width": w, "height": h})
            await pg.set_content(splash_html(w, h))
            await pg.wait_for_timeout(50)
            await pg.screenshot(path=str(out))

        await pg.set_viewport_size({"width": 1280, "height": 640})
        await pg.goto("file://" + str(ROOT / "README.md"))  # file:// origin so the font URL loads
        await pg.set_content(social_html())
        await pg.evaluate("document.fonts.ready")
        await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(ROOT / "social-preview.png"))
        await b.close()
    print("brand assets regenerated")

asyncio.run(main())
